/**
 * 给数组中的每个元素添加前缀
 */
function prependBullets(items: Array<string | string[]>): string[] {
  return items.flatMap((item) =>
    Array.isArray(item)
      ? item.map((subitem) => `  - ${subitem}`)
      : [` - ${item}`],
  );
}
